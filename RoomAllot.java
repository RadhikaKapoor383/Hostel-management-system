    private void AccCreateButton4ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_AccCreateButton4ActionPerformed
        String URL = "jdbc:mysql://localhost:3306/HostelDB";
        String Username = "root";
        String Password = "Radhika1@";

        try {
            Class.forName("com.mysql.cj.jdbc.Driver");
        } catch (ClassNotFoundException e) {
            System.out.println(e.getMessage());
        }

        try (Connection connect = DriverManager.getConnection(URL, Username, Password)) {

            if (allot.getText().equals("YYYY-MM-DD") || sid.getText().isEmpty() || room_id.getText().isEmpty()) {
                JOptionPane.showMessageDialog(this, "Please fill all fields.");
            } else if (!dateValidator(allot.getText())) {
                JOptionPane.showMessageDialog(this, "Please enter valid date format (YYYY-MM-DD).");

                if (!dateValidator(allot.getText())) {
                    allot.setBorder(BorderFactory.createLineBorder(Color.RED));
                }
            } else {
                int studentId = Integer.parseInt(sid.getText());
                int roomId = Integer.parseInt(room_id.getText());
                Date allotmentDate = StringToDate(allot.getText());

                String checkQuery = "SELECT capacity, occupied FROM HostelRooms WHERE room_id = ?";
                try (PreparedStatement checkStmt = connect.prepareStatement(checkQuery)) {
                    checkStmt.setInt(1, roomId);
                    ResultSet rs = checkStmt.executeQuery();

                    if (rs.next()) {
                        int capacity = rs.getInt("capacity");
                        int occupied = rs.getInt("occupied");

                        if (occupied >= capacity) {
                            JOptionPane.showMessageDialog(this, "Room is already full.");
                            return;
                        }

                        String insertQuery = "INSERT INTO RoomAllotment (student_id, room_id, allotment_date) VALUES (?, ?, ?)";
                        try (PreparedStatement insertStmt = connect.prepareStatement(insertQuery)) {
                            insertStmt.setInt(1, studentId);
                            insertStmt.setInt(2, roomId);
                            insertStmt.setDate(3, allotmentDate);
                            insertStmt.executeUpdate();
                        }

                        String updateRoom = "UPDATE HostelRooms SET occupied = occupied + 1 WHERE room_id = ?";
                        try (PreparedStatement updateStmt = connect.prepareStatement(updateRoom)) {
                            updateStmt.setInt(1, roomId);
                            updateStmt.executeUpdate();
                        }

                        JOptionPane.showMessageDialog(this, "Room has been allotted successfully!");


                    } else {
                        JOptionPane.showMessageDialog(this, "Room ID not found.");
                    }
                }

            }

        } catch (SQLException e) {
            e.printStackTrace();
            JOptionPane.showMessageDialog(this, "Database Error: " + e.getMessage());
        } catch (ParseException ex) {
            Logger.getLogger(RoomAllot.class.getName()).log(Level.SEVERE, null, ex);
        }

    }//GEN-LAST:event_AccCreateButton4ActionPerformed

    private Date StringToDate(String dateStr) throws ParseException {
        SimpleDateFormat formatter = new SimpleDateFormat("yyyy-MM-dd");
        java.util.Date date = formatter.parse(dateStr);
        return new Date(date.getTime());
    }
