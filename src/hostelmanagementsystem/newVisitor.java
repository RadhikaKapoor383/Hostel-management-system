    private void AddVisitorActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_AddVisitorActionPerformed
        String URL = "jdbc:mysql://localhost:3306/HostelDB";
        String Username = "root";
        String Password = "Radhika1@";

        try {
            Class.forName("com.mysql.cj.jdbc.Driver");
        } catch (ClassNotFoundException e) {
            System.out.println(e.getMessage());
        }

        try (Connection connect = DriverManager.getConnection(URL, Username, Password)) {

            if (Vname.getText().equals("") || relation.getText().equals("")
                    || vDate.getText().equals("YYYY-MM-DD")
                    || contact.getText().equals("03XX-XXXXXXX")
                    || Cnic.getText().equals("XXXXX-XXXXXX-X")) {

                JOptionPane.showMessageDialog(this, "Please enter data into all field(s)");

            } else if (!dateValidator(vDate.getText()) || !numberValidator(contact.getText()) || !cnicValidator(Cnic.getText())) {

                JOptionPane.showMessageDialog(this, "Please enter valid values!");

                if (!dateValidator(vDate.getText())) {
                    vDate.setBorder(BorderFactory.createLineBorder(Color.RED));
                }
                if (!numberValidator(contact.getText())) {
                    contact.setBorder(BorderFactory.createLineBorder(Color.RED));
                }
                if (!cnicValidator(Cnic.getText())) {
                    Cnic.setBorder(BorderFactory.createLineBorder(Color.RED));
                }

            } else {

                String query = "INSERT INTO visitors (student_id, visitor_name, relation, visit_date, contact_no, CNIC) VALUES (?, ?, ?, ?, ?, ?)";

                try (PreparedStatement statement = connect.prepareStatement(query)) {
                    statement.setString(1, sid.getText());
                    statement.setString(2, Vname.getText());
                    statement.setString(3, relation.getText());
                    statement.setDate(4, StringToDate(vDate.getText()));
                    statement.setString(5, contact.getText());
                    statement.setString(6, Cnic.getText());

                    int insertRow = statement.executeUpdate();
                    JOptionPane.showMessageDialog(this, "Visitor details updated successfully.");

                } catch (Exception ex) {
                    System.out.println(ex.getMessage());
                }
            }

        } catch (SQLException e) {
            System.out.println(e.getMessage());
        }
    }//GEN-LAST:event_AddVisitorActionPerformed

    private boolean dateValidator(String pass) {
        String regex = "^(19|20)\\d\\d-(0[1-9]|1[0-2])-(0[1-9]|[12]\\d|3[01])$";
        Pattern pattern = Pattern.compile(regex);
        Matcher matcher = pattern.matcher(vDate.getText());
        return matcher.matches();
    }

    private boolean numberValidator(String pass) {
        String regex = "^03\\d{2}-?\\d{7}$";
        Pattern pattern = Pattern.compile(regex);
        Matcher matcher = pattern.matcher(contact.getText());
        return matcher.matches();
    }

    private boolean cnicValidator(String pass) {
        String regex = "^\\d{5}-?\\d{6}-?\\d{1}$";
        Pattern pattern = Pattern.compile(regex);
        Matcher matcher = pattern.matcher(Cnic.getText());
        return matcher.matches();
    }
    private Date StringToDate(String dateStr) throws ParseException {
        SimpleDateFormat formatter = new SimpleDateFormat("yyyy-MM-dd");
        java.util.Date date = formatter.parse(dateStr);
        return new Date(date.getTime());
    }
    private void BackMainActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_BackMainActionPerformed
        String URL = "jdbc:mysql://localhost:3306/HostelDB";
        String username = "root";
        String Password = "Radhika1@";

        visitorRecord vr = new visitorRecord();

        try {
            Class.forName("com.mysql.cj.jdbc.Driver");
        } catch (ClassNotFoundException e) {
            System.out.println(e.getMessage());
        }

        try {

            DefaultTableModel model = (DefaultTableModel) vr.visitor.getModel();
            model.setColumnIdentifiers(new String[]{
                "Student ID",
                "Student Name",
                "Visitor Name",
                "Relation",
                "Visit date",
                "Contact number",
                "CNIC"
            });

            String query = "SELECT s.student_id, CONCAT(s.first_name, ' ', s.last_name) AS student_name, "
                    + "v.visitor_name, v.relation, v.visit_date, v.contact_no, v.CNIC FROM visitors v "
                    + "JOIN students s ON v.student_id = s.student_id";
            try (java.sql.Connection connect = DriverManager.getConnection(URL, username, Password);
                PreparedStatement stmt = connect.prepareStatement(query); ResultSet rs = stmt.executeQuery()) {
                while (rs.next()) {
                    Object[] row = {
                        rs.getString("student_id"),
                        rs.getString("student_name"),
                        rs.getString("visitor_name"),
                        rs.getString("relation"),
                        rs.getDate("visit_date"),
                        rs.getString("contact_no"),
                        rs.getString("CNIC")                        
                    };

                    model.addRow(row);
                }
            }

            dispose();

            vr.pack();
            vr.setLocationRelativeTo(null);
            vr.setVisible(true);
            vr.show();

        } catch (SQLException e) {
            System.out.println(e.getMessage());
        }
        
    }//GEN-LAST:event_BackMainActionPerformed

