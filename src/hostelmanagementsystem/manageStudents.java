    private void EditStudentActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_EditStudentActionPerformed
        String ID = JOptionPane.showInputDialog("Please enter the ID of student you want to edit :");
        int userID = Integer.parseInt(ID);
        String URL = "jdbc:mysql://localhost:3306/HostelDB";
        String username = "root";
        String password = "Radhika1@";
        String query = "select * from students where Student_id = ?";

        EditStudent editProfile = new EditStudent();
        try {
            Class.forName("com.mysql.cj.jdbc.Driver");
        } catch (ClassNotFoundException e) {
            System.out.println(e.getMessage());
        }

        try {
            Connection connect = DriverManager.getConnection(URL, username, password);
            PreparedStatement stmt = connect.prepareStatement(query);
            stmt.setInt(1, userID);
            ResultSet rs = stmt.executeQuery();

            if (rs.next()) {

                editProfile.Firstname.setText(rs.getString("first_name"));
                editProfile.lastName.setText(rs.getString("last_name"));
                editProfile.gender.setText(rs.getString("gender"));
                editProfile.DOB.setText(rs.getString("DOB"));
                editProfile.dept.setText(rs.getString("department"));
                editProfile.contact.setText(rs.getString("contact_no"));
                editProfile.Email.setText(rs.getString("email"));
                editProfile.CNIC.setText(rs.getString("CNIC"));
                editProfile.city.setText(rs.getString("city"));
                editProfile.Address.setText(rs.getString("address"));
                editProfile.sid.setText(rs.getString(("student_id")));

                editProfile.show();
                dispose();
            } else {
                JOptionPane.showMessageDialog(this, "This ID of Visitor does not exist.");
            }

        } catch (SQLException e) {
            System.out.println(e.getMessage());
        }
    }//GEN-LAST:event_EditStudentActionPerformed

