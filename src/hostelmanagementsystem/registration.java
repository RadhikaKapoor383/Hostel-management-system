    private void AccCreateButton4ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_AccCreateButton4ActionPerformed
        String URL = "jdbc:mysql://localhost:3306/HostelDB";
        String Username = "root";
        String Password = "Radhika1@";

        try {
            Class.forName("com.mysql.cj.jdbc.Driver");
        } catch (ClassNotFoundException e) {
            System.out.println(e.getMessage());
        }

        try (Connection connect = DriverManager.getConnection(URL, Username, Password)) {
            // Check for empty fields and valid input
            if (Firstname.getText().equals("") || lastName.getText().equals("")
                    || dob.getText().equals("YYYY-MM-DD") || Email.getText().equals("username@gmail.com")
                    || contact.getText().equals("03XX-XXXXXXX") || gender.getText().equals("")
                    || CNIC.getText().equals("XXXXX-XXXXXX-X") || CNIC.getText().equals("") || Address.getText().equals("")) {

                JOptionPane.showMessageDialog(this, "Please enter data into remaining field(s)");

            } else if (!dateValidator(dob.getText()) || !emailValidator(Email.getText())
                    || !numberValidator(contact.getText())
                    || !cnicValidator(CNIC.getText())) {

                JOptionPane.showMessageDialog(this, "Please enter valid values!");

                if (!dateValidator(dob.getText())) {
                    dob.setBorder(BorderFactory.createLineBorder(Color.RED));
                }
                if (!emailValidator(Email.getText())) {
                    Email.setBorder(BorderFactory.createLineBorder(Color.RED));
                }
                if (!numberValidator(contact.getText())) {
                    contact.setBorder(BorderFactory.createLineBorder(Color.RED));
                }
                if (!cnicValidator(CNIC.getText())) {
                    CNIC.setBorder(BorderFactory.createLineBorder(Color.RED));
                }

            } else {

                String query = "INSERT INTO Students (first_name, last_name, gender, DOB, department, contact_no, email, CNIC, City, Address) VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?)";
                try (PreparedStatement statement = connect.prepareStatement(query)) {
                    statement.setString(1, Firstname.getText());
                    statement.setString(2, lastName.getText());
                    statement.setString(3, gender.getText());
                    statement.setDate(4, StringToDate(dob.getText()));
                    statement.setString(5, department.getText());
                    statement.setString(6, contact.getText());
                    statement.setString(7, Email.getText());
                    statement.setString(8, CNIC.getText());
                    statement.setString(9, city.getText());
                    statement.setString(10, Address.getText());
                    int insertRow = statement.executeUpdate();
                    JOptionPane.showMessageDialog(this, "Student has been register.");

                } catch (Exception ex) {
                    System.out.println(ex.getMessage());
                }
            }

        } catch (SQLException e) {
            System.out.println(e.getMessage());
        }

    }//GEN-LAST:event_AccCreateButton4ActionPerformed

    private Date StringToDate(String dateStr) throws ParseException {
        SimpleDateFormat formatter = new SimpleDateFormat("yyyy-MM-dd");
        java.util.Date date = formatter.parse(dateStr);
        return new Date(date.getTime());
    }
