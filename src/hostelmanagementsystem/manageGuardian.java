    private void EditGuardianActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_EditGuardianActionPerformed
        String ID = JOptionPane.showInputDialog("Please enter the ID of guardian you want to edit:");

        if (ID == null || ID.trim().isEmpty()) {
            JOptionPane.showMessageDialog(this, "No ID entered. Operation cancelled.");
            return;
        }
        int userID = Integer.parseInt(ID);
        String URL = "jdbc:mysql://localhost:3306/HostelDB";
        String username = "root";
        String password = "Radhika1@";
        String query = "select * from guardian where g_id = ?";

        EditGuardian editProfile = new EditGuardian();
        try {
            Class.forName("com.mysql.cj.jdbc.Driver");
        } catch (ClassNotFoundException e) {
            System.out.println(e.getMessage());
        }

        try {
            Connection connect = DriverManager.getConnection(URL, username, password);
            PreparedStatement stmt = connect.prepareStatement(query);
            stmt.setInt(1, userID);
            ResultSet rs = stmt.executeQuery();

            if (rs.next()) {

                editProfile.Firstname.setText(rs.getString("first_name"));
                editProfile.lastName.setText(rs.getString("last_name"));
                editProfile.relation.setText(rs.getString("relation"));
                editProfile.contact.setText(rs.getString("Contact"));
                editProfile.Email.setText(rs.getString("email"));
                editProfile.CNIC.setText(rs.getString("CNIC"));
                editProfile.sid.setText(rs.getString(("student_id")));

                editProfile.show();
                dispose();
            } else {
                JOptionPane.showMessageDialog(this, "This ID of guardian does not exist.");
            }

        } catch (SQLException e) {
            System.out.println(e.getMessage());
        }
    }//GEN-LAST:event_EditGuardianActionPerformed

