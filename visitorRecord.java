    private void EditVisitorActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_EditVisitorActionPerformed
        String ID = JOptionPane.showInputDialog("Please enter the ID of visitor you want to edit :");
        int userID = Integer.parseInt(ID);
        String URL = "jdbc:mysql://localhost:3306/HostelDB";
        String username = "root";
        String password = "Radhika1@";
        String query = "select v.*, CONCAT(s.first_name, ' ', s.last_name) AS student_name from visitors v JOIN students s ON v.student_id = s.student_id where visitor_id = ?";

        EditVisitor editProfile = new EditVisitor();
        try {
            Class.forName("com.mysql.cj.jdbc.Driver");
        } catch (ClassNotFoundException e) {
            System.out.println(e.getMessage());
        }

        try {
            Connection connect = DriverManager.getConnection(URL, username, password);
            PreparedStatement stmt = connect.prepareStatement(query);
            stmt.setInt(1, userID);
            ResultSet rs = stmt.executeQuery();

            if (rs.next()) {

                editProfile.vname.setText(rs.getString("visitor_name"));
                editProfile.sname.setText(rs.getString("student_name"));
                editProfile.relation.setText(rs.getString("relation"));
                editProfile.vdate.setText(rs.getString("visit_date"));
                editProfile.contact.setText(rs.getString("Contact_no"));
                editProfile.cnic.setText(rs.getString("CNIC"));
                editProfile.vid.setText("" + userID);
                editProfile.sid.setText(rs.getString(("student_id")));

                editProfile.show();
                dispose();
            } else {
                JOptionPane.showMessageDialog(this, "This ID of Visitor does not exist.");
            }

        } catch (SQLException e) {
            System.out.println(e.getMessage());
        }
    }//GEN-LAST:event_EditVisitorActionPerformed

