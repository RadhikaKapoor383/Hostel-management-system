    private void roomAllocatedActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_roomAllocatedActionPerformed
        String URL = "jdbc:mysql://localhost:3306/HostelDB";
        String username = "root";
        String Password = "Radhika1@";

        roomAvailable rm = new roomAvailable();

        try {
            Class.forName("com.mysql.cj.jdbc.Driver");
        } catch (ClassNotFoundException e) {
            System.out.println(e.getMessage());
        }

        try {

            DefaultTableModel model = (DefaultTableModel) rm.avail.getModel();
            model.setColumnIdentifiers(new String[]{
                "Room ID",
                "Student ID",
                "Room no",
                "Room Type",
                "Capacity",
                "Occupied",
                "Allotment Date",
                "Leave Date"
            });

            String query = "SELECT r.room_id, ra.student_id, r.room_no, r.room_type, r.capacity, r.occupied,\n"
                    + "       ra.allotment_date, ra.leave_date\n"
                    + "FROM HostelRooms r\n"
                    + "JOIN roomAllotment ra ON r.room_id = ra.room_id\n"
                    + "WHERE ra.leave_date IS NULL";
            try (java.sql.Connection connect = DriverManager.getConnection(URL, username, Password); PreparedStatement stmt = connect.prepareStatement(query); ResultSet rs = stmt.executeQuery()) {
                while (rs.next()) {
                    Object[] row = {
                        rs.getInt("room_id"),
                        rs.getInt("student_id"),
                        rs.getString("room_no"),
                        rs.getString("room_type"),
                        rs.getInt("capacity"),
                        rs.getInt("occupied"),
                        rs.getDate("allotment_date"),
                        rs.getDate("leave_date")
                    };

                    model.addRow(row);
                }
            }

            dispose();

            rm.pack();
            rm.setLocationRelativeTo(null);
            rm.show();

        } catch (SQLException e) {
            System.out.println(e.getMessage());
        }
    }//GEN-LAST:event_roomAllocatedActionPerformed

