    private void BackMainActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_BackMainActionPerformed
        String URL = "jdbc:mysql://localhost:3306/HostelDB";
        String username = "root";
        String Password = "Radhika1@";

        roomManage rm = new roomManage();

        try {
            Class.forName("com.mysql.cj.jdbc.Driver");
        } catch (ClassNotFoundException e) {
            System.out.println(e.getMessage());
        }

        try {

            DefaultTableModel model = (DefaultTableModel) rm.rooms.getModel();
            model.setColumnIdentifiers(new String[]{
                "Room ID",
                "Student ID",
                "Room no",
                "Room Type",
                "Capacity",
                "Occupied",
                "Allocation Date",
                "Leave Date"
            });

            String query = "SELECT r.room_id, s.student_id, r.room_no, r.room_type, r.capacity, r.occupied, r.allotion_date, r.leave_date FROM HostelRooms r JOIN roomAllotment s ON r.room_id = s.room_id";
            try (java.sql.Connection connect = DriverManager.getConnection(URL, username, Password); PreparedStatement stmt = connect.prepareStatement(query); ResultSet rs = stmt.executeQuery()) {
                while (rs.next()) {
                    Object[] row = {
                        rs.getInt("room_id"),
                        rs.getInt("student_id"),
                        rs.getString("room_no"),
                        rs.getString("room_type"),
                        rs.getInt("capacity"),
                        rs.getInt("occupied"),
                        rs.getDate("Allotation_date"),
                        rs.getDate("leave_date")
                    };

                    model.addRow(row);
                }
            }

        } catch (SQLException e) {
            System.out.println(e.getMessage());
        }
    }//GEN-LAST:event_BackMainActionPerformed

    private boolean dateValidator(String pass) {
        String regex = "^(19|20)\\d\\d-(0[1-9]|1[0-2])-(0[1-9]|[12]\\d|3[01])$";
        Pattern pattern = Pattern.compile(regex);
        Matcher matcher = pattern.matcher(leave.getText());
        return matcher.matches();
    }

