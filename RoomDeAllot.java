    private void deAllotActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_deAllotActionPerformed
        String URL = "jdbc:mysql://localhost:3306/HostelDB";
        String Username = "root";
        String Password = "Radhika1@";

        try {
            Class.forName("com.mysql.cj.jdbc.Driver");
        } catch (ClassNotFoundException e) {
            System.out.println(e.getMessage());
        }

        try (Connection connect = DriverManager.getConnection(URL, Username, Password)) {

            if (leave.getText().equals("YYYY-MM-DD") || leave.getText().isEmpty()) {
                JOptionPane.showMessageDialog(this, "Please enter Leave Date.");
            } else if (!dateValidator(leave.getText())) {
                JOptionPane.showMessageDialog(this, "Please enter date in valid format (YYYY-MM-DD).");
                leave.setBorder(BorderFactory.createLineBorder(Color.RED));
            } else {
                int studentId = Integer.parseInt(sid.getText());
                int roomId = Integer.parseInt(rid.getText());
                Date leaveDate = StringToDate(leave.getText());

                
                String updateLeave = "UPDATE RoomAllotment SET leave_date = ? WHERE student_id = ? AND leave_date IS NULL";
                try (PreparedStatement leaveStmt = connect.prepareStatement(updateLeave)) {
                    leaveStmt.setDate(1, leaveDate);
                    leaveStmt.setInt(2, studentId);
                    leaveStmt.executeUpdate();
                }

                
                String updateRoom = "UPDATE HostelRooms SET occupied = occupied - 1 WHERE room_id = ?";
                try (PreparedStatement updateStmt = connect.prepareStatement(updateRoom)) {
                    updateStmt.setInt(1, roomId);
                    updateStmt.executeUpdate();
                }

                JOptionPane.showMessageDialog(this, "Student checked out successfully.");
                dispose();
                roomManage main = new roomManage();
                main.pack();
                main.setLocationRelativeTo(null);
                main.setVisible(true);
            }

        } catch (Exception e) {
            e.printStackTrace();
            JOptionPane.showMessageDialog(this, "Database Error: " + e.getMessage());
        }

    }//GEN-LAST:event_deAllotActionPerformed

    private Date StringToDate(String dateStr) throws ParseException {
        SimpleDateFormat formatter = new SimpleDateFormat("yyyy-MM-dd");
        java.util.Date date = formatter.parse(dateStr);
        return new Date(date.getTime());
    }
