    private void editVisitActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_editVisitActionPerformed
        String URL = "jdbc:mysql://localhost:3306/HostelDB";
        String Username = "root";
        String Password = "Radhika1@";

        try {
            Class.forName("com.mysql.cj.jdbc.Driver");
        } catch (ClassNotFoundException e) {
            System.out.println(e.getMessage());
        }

        try (Connection connect = DriverManager.getConnection(URL, Username, Password)) {


            if (vname.getText().equals("") || relation.getText().equals("")
                    || vdate.getText().equals("YYYY-MM-DD")
                    || contact.getText().equals("03XX-XXXXXXX")
                    || cnic.getText().equals("XXXXX-XXXXXX-X")) {

                    JOptionPane.showMessageDialog(this, "Please enter data into remaining field(s)");
                

            } else if (!dateValidator(vdate.getText()) || !numberValidator(contact.getText()) || !cnicValidator(cnic.getText())) {

                JOptionPane.showMessageDialog(this, "Please enter valid values!");

                if (!dateValidator(vdate.getText())) {
                    vdate.setBorder(BorderFactory.createLineBorder(Color.RED));
                }
                if (!numberValidator(contact.getText())) {
                    contact.setBorder(BorderFactory.createLineBorder(Color.RED));
                }
                if (!cnicValidator(cnic.getText())) {
                    cnic.setBorder(BorderFactory.createLineBorder(Color.RED));
                }

            } else {

                String query = "UPDATE visitors SET visitor_name = ?, relation = ?, visit_date = ?, contact_no = ?, CNIC = ? WHERE visitor_id = ?";

                try (PreparedStatement statement = connect.prepareStatement(query)) {
                    statement.setString(1, vname.getText());
                    statement.setString(2, relation.getText());
                    statement.setDate(3, StringToDate(vdate.getText()));
                    statement.setString(4, contact.getText());
                    statement.setString(5, cnic.getText());
                    statement.setString(6, vid.getText());

                    int updateRow = statement.executeUpdate();

                    if (updateRow > 0) {
                        JOptionPane.showMessageDialog(this, "Visitor details updated successfully.");

                    } else {
                        JOptionPane.showMessageDialog(this, "Visitor not found or update failed.");
                    }
                } catch (Exception ex) {
                    System.out.println(ex.getMessage());
                }
            }

        } catch (SQLException e) {
            System.out.println(e.getMessage());
        }

    }//GEN-LAST:event_editVisitActionPerformed

    private void BackMainActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_BackMainActionPerformed
        String URL = "jdbc:mysql://localhost:3306/HostelDB";
        String username = "root";
        String Password = "Radhika1@";

        visitorRecord vr = new visitorRecord();

        try {
            Class.forName("com.mysql.cj.jdbc.Driver");
        } catch (ClassNotFoundException e) {
            System.out.println(e.getMessage());
        }

        try {

            DefaultTableModel model = (DefaultTableModel) vr.visitor.getModel();

            String query = "SELECT s.student_id, CONCAT(s.first_name, ' ', s.last_name) AS student_name, "
                    + "v.visitor_name, v.relation, v.visit_date, v.contact_no, v.CNIC FROM visitors v "
                    + "JOIN students s ON v.student_id = s.student_id";
            try (java.sql.Connection connect = DriverManager.getConnection(URL, username, Password); PreparedStatement stmt = connect.prepareStatement(query); ResultSet rs = stmt.executeQuery()) {
                while (rs.next()) {
                    Object[] row = {
                        rs.getString("student_id"),
                        rs.getString("student_name"),
                        rs.getString("visitor_name"),
                        rs.getString("relation"),
                        rs.getDate("visit_date"),
                        rs.getString("contact_no"),
                        rs.getString("CNIC")
                    };

                    model.addRow(row);
                }
            }

            dispose();

            vr.pack();
            vr.setLocationRelativeTo(null);
            vr.setVisible(true);
            vr.show();

        } catch (SQLException e) {
            System.out.println(e.getMessage());
        }
    }//GEN-LAST:event_BackMainActionPerformed

