    private void AccCreateButton4ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_AccCreateButton4ActionPerformed
        String URL = "jdbc:mysql://localhost:3306/HostelDB";
        String Username = "root";
        String Password = "Radhika1@";

        try {
            Class.forName("com.mysql.cj.jdbc.Driver");
        } catch (ClassNotFoundException e) {
            System.out.println(e.getMessage());
        }

        try (Connection connect = DriverManager.getConnection(URL, Username, Password)) {
            // Check for empty fields and valid input
            if (Firstname.getText().equals("") || lastName.getText().equals("")
                || Email.getText().equals("username@gmail.com")
                || contact.getText().equals("03XX-XXXXXXX")
                || CNIC.getText().equals("XXXXX-XXXXXX-X") || CNIC.getText().equals("")) {

                JOptionPane.showMessageDialog(this, "Please enter data into remaining field(s)");

            } else if (!emailValidator(Email.getText())
                || !numberValidator(contact.getText())
                || !cnicValidator(CNIC.getText())) {

                JOptionPane.showMessageDialog(this, "Please enter valid values!");

                if (!emailValidator(Email.getText())) {
                    Email.setBorder(BorderFactory.createLineBorder(Color.RED));
                }
                if (!numberValidator(contact.getText())) {
                    contact.setBorder(BorderFactory.createLineBorder(Color.RED));
                }
                if (!cnicValidator(CNIC.getText())) {
                    CNIC.setBorder(BorderFactory.createLineBorder(Color.RED));
                }

            } else {

                String query = "UPDATE guardian SET first_name = ?, last_name = ?, relation = ?,"
                        + " contact = ?, email = ? , CNIC = ? WHERE student_id = ?";

                try (PreparedStatement statement = connect.prepareStatement(query)) {
                    statement.setString(1, Firstname.getText());
                    statement.setString(2, lastName.getText());
                    statement.setString(3, relation.getText());
                    statement.setString(4, contact.getText());
                    statement.setString(5, Email.getText());
                    statement.setString(6, CNIC.getText());
                    statement.setString(7, sid.getText());

                    int updateRow = statement.executeUpdate();

                    if (updateRow > 0) {
                        JOptionPane.showMessageDialog(this, "Guardian details updated successfully.");
                        dispose();

                    } else {
                        JOptionPane.showMessageDialog(this, "guardian not found or update failed.");
                    }
                }catch (Exception ex) {
                    System.out.println(ex.getMessage());
                }
            }

        } catch (SQLException e) {
            System.out.println(e.getMessage());
        }
    }//GEN-LAST:event_AccCreateButton4ActionPerformed

    private void BackMainActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_BackMainActionPerformed
        String URL = "jdbc:mysql://localhost:3306/HostelDB";
        String username = "root";
        String Password = "Radhika1@";

        manageGuardian vr = new manageGuardian();

        try {
            Class.forName("com.mysql.cj.jdbc.Driver");
        } catch (ClassNotFoundException e) {
            System.out.println(e.getMessage());
        }

        try {

            DefaultTableModel model = (DefaultTableModel) vr.guardian.getModel();


            String query = "SELECT s.student_id, CONCAT(s.first_name, ' ', s.last_name) AS Student_name, "
                    + "CONCAT(g.first_name, ' ', g.last_name) AS Guardian_name, "
                    + "g.relation, g.contact, g.email, g.CNIC FROM Guardian g "
                    + "JOIN students s ON g.student_id = s.student_id";
            try (java.sql.Connection connect = DriverManager.getConnection(URL, username, Password); 
                    PreparedStatement stmt = connect.prepareStatement(query); 
                    ResultSet rs = stmt.executeQuery()) {
                while (rs.next()) {
                    Object[] row = {
                        rs.getInt("student_id"),
                        rs.getString("student_name"),
                        rs.getString("guardian_name"),
                        rs.getString("relation"),
                        rs.getString("contact"),
                        rs.getString("email"),
                        rs.getString("CNIC")};

                    model.addRow(row);
                }
            }

            dispose();

            vr.pack();
            vr.setLocationRelativeTo(null);
            vr.show();

        } catch (SQLException e) {
            System.out.println(e.getMessage());
        }
    }//GEN-LAST:event_BackMainActionPerformed

